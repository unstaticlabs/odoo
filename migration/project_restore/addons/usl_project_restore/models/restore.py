    def _issue(self, severity, source_model, source_id, description):
        self.ensure_one()
        return self.env["usl.project.restore.issue"].create(
            {
                "run_id": self.id,
                "severity": severity,
                "source_model": source_model,
                "source_id": source_id or 0,
                "description": description,
            },
        )

    @staticmethod
    def _source_text(value):
        if isinstance(value, dict):
            return (
                value.get("en_US")
                or value.get("fr_FR")
                or next(iter(value.values()), "")
            )
        return value or ""

    @staticmethod
    def _source_translation(value, language):
        return value.get(language) if isinstance(value, dict) else False

    def _remove_generated_onboarding_todos(self):
        """Remove only untouched private tasks generated by project_todo.

        Installing Project and restoring users can create one welcome to-do per
        user.  Those records are distribution onboarding fixtures, not source
        business data.  Match the rendered native template exactly so a user
        edited task, or any other target-only task, is never removed.
        """
        candidates = (
            self.env["project.task"]
            .sudo()
            .with_context(active_test=False)
            .search(
                [
                    ("rebuild_source_id", "=", False),
                    ("project_id", "=", False),
                    ("partner_id", "=", False),
                    ("company_id", "=", False),
                    ("create_uid", "=", SUPERUSER_ID),
                ],
            )
        )
        generated = self.env["project.task"]
        for task in candidates:
            if len(task.user_ids) != 1:
                continue
            user = task.user_ids
            languages = {user.lang or self.env.user.lang, "en_US"}
            for language in languages:
                localized = user.with_context(lang=language)
                body = localized.env["ir.qweb"]._render(
                    "project_todo.todo_user_onboarding",
                    {"object": user},
                    minimal_qcontext=True,
                    raise_if_not_found=False,
                )
                title = localized.env._("Welcome %s!", user.name)
                if (
                    body
                    and task.name == title
                    and html_sanitize(task.description or "")
                    == html_sanitize(str(body))
                ):
                    generated |= task
                    break
        if generated:
            generated.unlink()
        return len(generated)

    def _acquire_preserved_primary_id_control(self, payload):
        """Lock Project writes and reject ambiguous source identities."""
        self.ensure_one()
        historical_stage_ids = payload.get("historical_task_stage_ids", [])
        specifications = (
            (
                "project.project.stage",
                "project_project_stage",
                payload.get("project_stages", []),
            ),
            ("project.project", "project_project", payload["projects"]),
            ("project.task", "project_task", payload["tasks"]),
            ("project.task.type", "project_task_type", payload["task_stages"]),
            (
                "project.task.type.history",
                "project_task_type",
                [{"id": stage_id} for stage_id in historical_stage_ids],
            ),
        )
        source_ids_by_model = {}
        for model_name, _table, rows in specifications:
            source_ids = [row.get("id") for row in rows]
            invalid_ids = [
                source_id
                for source_id in source_ids
                if isinstance(source_id, bool)
                or not isinstance(source_id, int)
                or source_id <= 0
            ]
            if invalid_ids:
                raise RuntimeError(
                    f"{model_name} contains invalid Online IDs: {invalid_ids!r}.",
                )
            if len(source_ids) != len(set(source_ids)):
                raise RuntimeError(
                    f"{model_name} contains duplicate Online IDs.",
                )
            source_ids_by_model[model_name] = source_ids
        overlapping_stage_ids = set(
            source_ids_by_model["project.task.type"],
        ) & set(source_ids_by_model["project.task.type.history"])
        if overlapping_stage_ids:
            raise RuntimeError(
                "Live and deleted historical task-stage IDs overlap: "
                f"{sorted(overlapping_stage_ids)!r}.",
            )

        self.env.flush_all()
        self.env.cr.execute(
            "LOCK TABLE project_project, project_project_stage, project_task, "
            "project_task_type IN ACCESS EXCLUSIVE MODE",
        )
        self._adopt_compatible_project_stage_fixtures(
            payload.get("project_stages", []),
        )
        self._remove_task_stage_id_collisions(source_ids_by_model)
        collisions = []
        for model_name, table, _rows in specifications:
            source_ids = source_ids_by_model[model_name]
            if not source_ids:
                continue
            self.env.cr.execute(
                f"""
                    SELECT id,
                           rebuild_source_database,
                           rebuild_source_model,
                           rebuild_source_id
                      FROM {table}
                     WHERE id = ANY(%s)
                        OR (
                            rebuild_source_model = %s
                            AND rebuild_source_id = ANY(%s)
                        )
                     ORDER BY id
                """,
                (source_ids, model_name, source_ids),
            )
            for record_id, database, traced_model, traced_id in self.env.cr.fetchall():
                same_source_identity = (
                    database == self.source_database
                    and traced_model == model_name
                    and traced_id == record_id
                )
                if record_id in source_ids and not same_source_identity:
                    collisions.append(
                        f"{model_name} Online ID {record_id} is occupied",
                    )
                elif traced_id in source_ids and record_id != traced_id:
                    collisions.append(
                        f"{model_name} Online ID {traced_id} is already mapped "
                        f"to target ID {record_id}",
                    )
        if collisions:
            raise RuntimeError(
                "Cannot preserve Project primary IDs: " + "; ".join(collisions),
            )

    def _adopt_compatible_project_stage_fixtures(self, rows):
        """Reuse exact-ID native stages only when they are safe equivalents.

        A clean Community installation owns the four native Project stages at
        the same primary IDs as Online. Creating duplicate traced stages would
        remap every project and make the native duration ledger invalid. Keep
        the native XML-ID owner, but adopt the record only when it is untraced,
        unreferenced, and semantically identical to the frozen source row.
        """
        Stage = self.env["project.project.stage"].sudo().with_context(
            active_test=False,
            lang="en_US",
            tracking_disable=True,
        )
        for row in rows:
            stage = Stage.browse(row["id"]).exists()
            if not stage or stage.rebuild_source_model or stage.rebuild_source_id:
                continue
            self.env.cr.execute(
                "SELECT count(*) FROM project_project WHERE stage_id = %s",
                (stage.id,),
            )
            referenced = self.env.cr.fetchone()[0]
            self.env.cr.execute(
                """
                    SELECT 1
                      FROM ir_model_data
                     WHERE module = 'project'
                       AND model = 'project.project.stage'
                       AND res_id = %s
                """,
                (stage.id,),
            )
            native_fixture = bool(self.env.cr.fetchone())
            semantic_equivalent = (
                stage.name == self._source_text(row["name"])
                and stage.sequence == row["sequence"]
                and stage.color == (row["color"] or 0)
                and stage.active == row["active"]
                and stage.fold == bool(row["fold"])
                and stage.rotting_threshold_days
                == (row["rotting_threshold_days"] or 0)
            )
            compatible = (
                not referenced
                and not row["company_id"]
                and not stage.company_id
                and (native_fixture or semantic_equivalent)
            )
            if not compatible:
                continue
            trace = self._trace_values(
                "project.project.stage",
                row["id"],
                self.source_snapshot,
                status="reused",
            )
            self.env.cr.execute(
                """
                    UPDATE project_project_stage
                       SET rebuild_source_database = %s,
                           rebuild_source_model = %s,
                           rebuild_source_id = %s,
                           rebuild_source_snapshot = %s,
                           rebuild_import_status = %s,
                           rebuild_import_note = %s
                     WHERE id = %s
                """,
                (
                    trace["rebuild_source_database"],
                    trace["rebuild_source_model"],
                    trace["rebuild_source_id"],
                    trace["rebuild_source_snapshot"],
                    trace["rebuild_import_status"],
                    trace["rebuild_import_note"],
                    stage.id,
                ),
            )
            stage.invalidate_recordset(
                [
                    "rebuild_source_database",
                    "rebuild_source_model",
                    "rebuild_source_id",
                    "rebuild_source_snapshot",
                    "rebuild_import_status",
                    "rebuild_import_note",
                ],
            )

    def _remove_task_stage_id_collisions(self, source_ids_by_model):
        """Discard only unowned target fixtures blocking source stage IDs."""
        expected_identity = {
            stage_id: model_name
            for model_name in (
                "project.task.type",
                "project.task.type.history",
            )
            for stage_id in source_ids_by_model[model_name]
        }
        stage_ids = list(expected_identity)
        if not stage_ids:
            return
        self.env.cr.execute(
            """
                SELECT id, rebuild_source_database, rebuild_source_model,
                       rebuild_source_id
                  FROM project_task_type
                 WHERE id = ANY(%s)
                 ORDER BY id
            """,
            (stage_ids,),
        )
        removable_ids = []
        for record_id, database, source_model, source_id in self.env.cr.fetchall():
            if (
                database == self.source_database
                and source_model == expected_identity[record_id]
                and source_id == record_id
            ):
                continue
            if source_model or source_id or database:
                continue
            removable_ids.append(record_id)
        if not removable_ids:
            return

        references = []
        for label, query in (
            (
                "tasks",
                "SELECT count(*) FROM project_task WHERE stage_id = ANY(%s)",
            ),
            (
                "projects",
                "SELECT count(*) FROM project_task_type_rel "
                "WHERE type_id = ANY(%s)",
            ),
            (
                "personal task links",
                "SELECT count(*) FROM project_task_user_rel "
                "WHERE stage_id = ANY(%s)",
            ),
            (
                "external IDs",
                "SELECT count(*) FROM ir_model_data "
                "WHERE model = 'project.task.type' AND res_id = ANY(%s)",
            ),
        ):
            self.env.cr.execute(query, (removable_ids,))
            count = self.env.cr.fetchone()[0]
            if count:
                references.append(f"{count} {label}")
        if references:
            raise RuntimeError(
                "Cannot reserve Online task-stage IDs because target fixtures "
                f"{removable_ids!r} still own " + ", ".join(references) + ".",
            )

        # These target fixture stages have no task, project, personal-stage, or
        # external-ID owner, so replacing their IDs cannot erase business data.
        self.env.cr.execute(
            "DELETE FROM project_task_type WHERE id = ANY(%s)",
            (removable_ids,),
        )
        self.env["project.task.type"].invalidate_model()

    def _reset_preserved_primary_id_sequences(self):
        self.ensure_one()
        for table in (
            "project_project",
            "project_project_stage",
            "project_task",
            "project_task_type",
        ):
            self.env.cr.execute(
                f"""
                    SELECT setval(
                        pg_get_serial_sequence('{table}', 'id'),
                        COALESCE(max(id), 0) + 1,
                        FALSE
                    )
                      FROM {table}
                """,
            )

    def _community_property_definition(self, definition):
        definition = copy.deepcopy(definition or [])
        field = self.env["project.project"]._fields[
            "task_properties_definition"
        ]
        allowed = set(field.ALLOWED_KEYS)
        allowed.update(
            self.env["base"]._additional_allowed_keys_properties_definition(),
        )
        for item in definition:
            for key in set(item) - allowed:
                item.pop(key)
        return definition

    def _trace_values(self, source_model, source_id, snapshot, status="imported"):
        return {
            "rebuild_source_database": self.source_database,
            "rebuild_source_model": source_model,
            "rebuild_source_id": source_id,
            "rebuild_source_snapshot": snapshot,
            "rebuild_import_status": status,
            "rebuild_import_note": (
                f"Restored by Projects run {self.id}, revision "
                f"{RESTORE_REVISION} from "
                f"{self.source_database}."
            ),
        }

    def _is_current_revision(self, record, snapshot):
        return bool(
            record
            and record.rebuild_source_snapshot == snapshot
            and f"revision {RESTORE_REVISION} " in (
                record.rebuild_import_note or ""
            ),
        )

    def _written_this_run(self, record):
        return bool(
            record
            and (
                f"Projects run {self.id}, revision {RESTORE_REVISION} "
                in (record.rebuild_import_note or "")
            ),
        )

    def _traced(self, target_model, source_model, source_ids):
        source_ids = [source_id for source_id in source_ids if source_id]
        if not source_ids:
            return {}
        records = (
            self.env[target_model]
            .with_context(active_test=False)
            .sudo()
            .search(
                [
                    ("rebuild_source_model", "=", source_model),
                    ("rebuild_source_id", "in", source_ids),
                ],
            )
        )
        result = {}
        for record in records.sorted("id"):
            if record.rebuild_source_id in result:
                self._issue(
                    "error",
                    source_model,
                    record.rebuild_source_id,
                    (
                        "Multiple target records carry this source identity; "
                        f"kept target {result[record.rebuild_source_id].id}."
                    ),
                )
                continue
            result[record.rebuild_source_id] = record
        return result

    def _upsert(
        self,
        target_model,
        source_model,
        row,
        values,
        snapshot,
        *,
        preserve_primary_id=False,
        translation_fields=(),
    ):
        traced = self._traced(target_model, source_model, [row["id"]])
        record = traced.get(row["id"])
        trace_values = self._trace_values(
            source_model,
            row["id"],
            snapshot,
        )
        values = {
            **values,
            **trace_values,
        }
        model = (
            self.env[target_model]
            .sudo()
            .with_context(
                active_test=False,
                tracking_disable=True,
                mail_create_nolog=True,
                mail_create_nosubscribe=True,
                mail_auto_subscribe_no_notify=True,
            )
        )
        if record:
            if preserve_primary_id and record.id != row["id"]:
                raise RuntimeError(
                    f"{source_model} Online ID {row['id']} is mapped to "
                    f"target ID {record.id}.",
                )
            if self._is_current_revision(record, snapshot):
                return record
            record.with_context(
                tracking_disable=True,
                mail_auto_subscribe_no_notify=True,
            ).write(values)
        else:
            create_model = model
            if preserve_primary_id:
                create_model = model.with_context(
                    **{SOURCE_PRIMARY_ID_CONTEXT: row["id"]},
                )
            record = create_model.create(values)
        if preserve_primary_id and record.id != row["id"]:
            raise RuntimeError(
                f"Failed to allocate {source_model} Online ID {row['id']}; "
                f"the ORM returned target ID {record.id}.",
            )
        if (
            record.rebuild_source_model != source_model
            or record.rebuild_source_id != row["id"]
            or record.rebuild_source_snapshot != snapshot
            or record.rebuild_import_note != trace_values["rebuild_import_note"]
        ):
            record.with_context(
                tracking_disable=True,
                mail_auto_subscribe_no_notify=True,
            ).write(trace_values)
        for field_name in translation_fields:
            translated = self._source_translation(row.get(field_name), "fr_FR")
            if translated and translated != self._source_text(row.get(field_name)):
                record.with_context(lang="fr_FR", tracking_disable=True).write(
                    {field_name: translated},
                )
        return record

    def _stamp_audit(self, model_name, record, row, user_map):
        if not self._written_this_run(record):
            return
        table_by_model = {
            "project.project": "project_project",
            "project.project.stage": "project_project_stage",
            "project.task": "project_task",
            "project.task.type": "project_task_type",
            "project.tags": "project_tags",
            "project.milestone": "project_milestone",
            "project.task.recurrence": "project_task_recurrence",
            "project.update": "project_update",
            "ir.attachment": "ir_attachment",
            "mail.message": "mail_message",
            "mail.activity": "mail_activity",
        }
        table = table_by_model.get(model_name)
        if not table:
            return
        create_uid = user_map.get(row.get("create_uid")) or self.env.user
        write_uid = user_map.get(row.get("write_uid")) or create_uid
        self.env.cr.execute(
            f"""
                UPDATE {table}
                   SET create_date = COALESCE(%s, create_date),
                       write_date = COALESCE(%s, write_date),
                       create_uid = %s,
                       write_uid = %s
                 WHERE id = %s
            """,
            (
                row.get("create_date"),
                row.get("write_date"),
                create_uid.id,
                write_uid.id,
                record.id,
            ),
        )
        record.invalidate_recordset(["create_date", "write_date"])

    def _target_xmlid(self, source_xmlids, source_model, source_id):
        xmlid = source_xmlids.get((source_model, source_id))
        if not xmlid:
            return self.env[source_model]
        try:
            record = self.env.ref(xmlid, raise_if_not_found=False)
        except ValueError:
            record = False
        return record or self.env[source_model]

    def _restore_partners_companies_users(self, payload, snapshot):
        companies = self._traced(
            "res.company",
            "res.company",
            [row["id"] for row in payload["companies"]],
        )
        for row in payload["companies"]:
            if row["id"] in companies:
                continue
            name = self._source_text(row["name"])
            company = self.env["res.company"].sudo().search(
                [("name", "=", name)],
                limit=1,
            )
            if not company:
                self._issue(
                    "error",
                    "res.company",
                    row["id"],
                    f"No target company matches {name!r}.",
                )
                continue
            company.write(
                self._trace_values(
                    "res.company",
                    row["id"],
                    snapshot,
                    status="reused",
                ),
            )
            companies[row["id"]] = company

        partners = self._traced(
            "res.partner",
            "res.partner",
            [row["id"] for row in payload["partners"]],
        )
        user_partner_by_source_id = {}
        for row in payload["users"]:
            target_user = (
                self.env["res.users"]
                .with_context(active_test=False)
                .sudo()
                .search([("login", "=", row["login"])], limit=1)
            )
            if target_user:
                user_partner_by_source_id[row["partner_id"]] = (
                    target_user.partner_id
                )
        partner_rows_by_id = {
            row["id"]: row for row in payload["partners"]
        }
        for source_id, partner in list(partners.items()):
            row = partner_rows_by_id[source_id]
            user_partner = user_partner_by_source_id.get(source_id)
            user_identity_conflicts = (
                user_partner and partner != user_partner
            )
            partner_name_conflicts = (
                row.get("name")
                and partner.name
                and partner.name != row["name"]
            )
            if user_identity_conflicts or partner_name_conflicts:
                partners.pop(source_id)
        for row in payload["partners"]:
            user_partner = user_partner_by_source_id.get(row["id"])
            if row["id"] in partners and (
                not user_partner or partners[row["id"]] == user_partner
            ):
                continue
            partner = user_partner
            if not partner:
                claimed_partner_ids = [
                    partner.id for partner in partners.values()
                ]
                identity_domains = []
                if row.get("name") and row.get("email"):
                    identity_domains.append(
                        [
                            ("name", "=", row["name"]),
                            ("email", "=ilike", row["email"]),
                        ],
                    )
                if row.get("name"):
                    identity_domains.append([("name", "=", row["name"])])
                if row.get("email"):
                    identity_domains.append(
                        [("email", "=ilike", row["email"])],
                    )
                for domain in identity_domains:
                    if claimed_partner_ids:
                        domain.append(("id", "not in", claimed_partner_ids))
                    domain.extend(
                        [
                            "|",
                            ("rebuild_source_id", "=", False),
                            "&",
                            ("rebuild_source_model", "=", "res.partner"),
                            ("rebuild_source_id", "=", row["id"]),
                        ],
                    )
                    candidates = (
                        self.env["res.partner"]
                        .with_context(active_test=False)
                        .sudo()
                        .search(domain, limit=2)
                    )
                    if len(candidates) == 1:
                        partner = candidates
                        break
            status = "reused"
            if (
                partner
                and partner.rebuild_source_model == "res.partner"
                and partner.rebuild_source_id
                and partner.rebuild_source_id != row["id"]
            ):
                self._issue(
                    "error",
                    "res.partner",
                    row["id"],
                    "The matched partner already belongs to another source "
                    "identity; the existing accounting identity was preserved.",
                )
                continue
            if not partner:
                status = "imported"
                partner = self.env["res.partner"].sudo().create(
                    {
                        "name": row["name"] or f"Source partner {row['id']}",
                        "email": row.get("email"),
                        "active": row.get("active", True),
                        "is_company": bool(row.get("is_company")),
                        "company_id": (
                            companies.get(row.get("company_id")).id
                            if companies.get(row.get("company_id"))
                            else False
                        ),
                    },
                )
            partner.write(
                self._trace_values(
                    "res.partner",
                    row["id"],
                    snapshot,
                    status=status,
                ),
            )
            partners[row["id"]] = partner

        users = {}
        default_password = os.getenv("PROJECT_RESTORE_DEFAULT_PASSWORD")
        for row in payload["users"]:
            partner = partners.get(row["partner_id"])
            if not partner:
                self._issue(
                    "error",
                    "res.users",
                    row["id"],
                    "User partner could not be reconciled.",
                )
                continue
            user = (
                self.env["res.users"]
                .with_context(active_test=False)
                .sudo()
                .search(
                    [
                        "|",
                        ("partner_id", "=", partner.id),
                        ("login", "=", row["login"]),
                    ],
                    limit=1,
                )
            )
            company_ids = [
                companies[source_company_id].id
                for source_company_id in row["company_ids"]
                if source_company_id in companies
            ]
            if not user:
                user_values = {
                    "name": partner.name,
                    "login": row["login"],
                    "email": partner.email,
                    "partner_id": partner.id,
                    "active": row["active"],
                    "share": row["share"],
                    "company_ids": [Command.set(company_ids)],
                    "company_id": company_ids[0] if company_ids else False,
                }
                if default_password:
                    user_values["password"] = default_password
                user = (
                    self.env["res.users"]
                    .with_context(no_reset_password=True)
                    .sudo()
                    .create(user_values)
                )
            groups = self.env["res.groups"]
            for xmlid in row["project_group_xmlids"]:
                group = self.env.ref(xmlid, raise_if_not_found=False)
                if group:
                    groups |= group
            project_user = self.env.ref(
                "project.group_project_user",
                raise_if_not_found=False,
            )
            if project_user and not row["share"]:
                groups |= project_user
            values = {"group_ids": [Command.link(group.id) for group in groups]}
            if company_ids:
                values["company_ids"] = [Command.link(item) for item in company_ids]
            user.sudo().write(values)
            users[row["id"]] = user
        return companies, partners, users

