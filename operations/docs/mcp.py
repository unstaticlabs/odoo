"""Render the MCP reference page from the pinned odoo-mcp catalogue.

The Odoo MCP server documents its own tools, profiles and conventions in
``docs/tool-catalogue.md`` of its repository. The distribution pins one
commit of that server (``deploy/odoo-mcp/release.json``), so the page the
user guide ships must describe exactly that commit, never the catalogue of
whatever is on the server's main branch. This module fetches the catalogue
at the pinned commit, from a local checkout when one is given and from the
GitHub contents API otherwise, and writes it as
``docs/users/reference/mcp-tools.md`` with the guide's front matter. The
catalogue's own heading gives way to the page title and its relative links
to other server documents are pinned to the same commit on GitHub.

``scripts/docs mcp render`` writes the page; ``scripts/docs mcp check``
recomputes it and fails when the committed page differs, which is how a
bump of the pin without ``make docs-mcp`` is caught in the release.
"""

from __future__ import annotations

import json
import posixpath
import re
import subprocess
from pathlib import Path

from operations.docs import ROOT, USERS, frontmatter

PAGE = Path("reference") / "mcp-tools.md"
RELEASE = Path("deploy") / "odoo-mcp" / "release.json"
COMPATIBILITY = Path("deploy") / "odoo-mcp" / "compatibility.json"
CATALOGUE = "docs/tool-catalogue.md"
GITHUB_REPOSITORY = "unstaticlabs/odoo-mcp"
TITLE = "MCP tools and profiles"
APP = "Agents & MCP"
DESCRIPTION = "The tools, profiles and conventions of the pinned Odoo MCP server, from its own catalogue."
GENERATED_NOTE = "<!-- Generated by `scripts/docs mcp` from the pinned odoo-mcp catalogue. Bump the pin, then run `make docs-mcp`. -->"
_LINK_RE = re.compile(r"(!?\[[^\]]*\]\()([^)\s]+)((?:\s+\"[^\"]*\")?\))")
_SHA_RE = re.compile(r"[0-9a-f]{40}")


class DocsMcpError(RuntimeError):
    """The pin is unreadable or the catalogue could not be fetched."""


# --- The pin -----------------------------------------------------------------


def pinned(root=ROOT):
    """Return ``(commit, version)`` from the release and compatibility files."""
    release = json.loads((root / RELEASE).read_text(encoding="utf-8"))
    commit = release.get("commit")
    if not isinstance(commit, str) or not _SHA_RE.fullmatch(commit):
        raise DocsMcpError(f"{RELEASE.as_posix()}: commit must be a full sha")
    compatibility = json.loads((root / COMPATIBILITY).read_text(encoding="utf-8"))
    version = compatibility.get("mcp_server_version")
    if not isinstance(version, str) or not version:
        raise DocsMcpError(f"{COMPATIBILITY.as_posix()}: mcp_server_version is missing")
    return commit, version


# --- The catalogue -----------------------------------------------------------


def _run(arguments):
    process = subprocess.run(arguments, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    if process.returncode:
        raise DocsMcpError(process.stderr.strip() or process.stdout.strip() or " ".join(arguments))
    return process.stdout


def fetch_catalogue(commit, repository=None):
    """Return the catalogue text at ``commit``.

    A local checkout is read with ``git show`` and needs the commit present;
    without one the GitHub contents API serves the raw file through ``gh``,
    which carries the credentials the private repository needs.
    """
    if repository:
        return _run(("git", "-C", str(repository), "show", f"{commit}:{CATALOGUE}"))
    return _run((
        "gh", "api", f"repos/{GITHUB_REPOSITORY}/contents/{CATALOGUE}?ref={commit}",
        "-H", "Accept: application/vnd.github.raw",
    ))


# --- Rendering ---------------------------------------------------------------


def _pin_links(body, commit):
    """Point the catalogue's relative links at the same commit on GitHub."""
    def replace(match):
        target = match.group(2)
        if target.startswith(("http://", "https://", "mailto:", "#", "/")):
            return match.group(0)
        path, _, fragment = target.partition("#")
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(CATALOGUE), path))
        url = f"https://github.com/{GITHUB_REPOSITORY}/blob/{commit}/{resolved}"
        if fragment:
            url = f"{url}#{fragment}"
        return f"{match.group(1)}{url}{match.group(3)}"
    return _LINK_RE.sub(replace, body)


def _demote_title(body):
    """Drop the catalogue's own ``# `` heading; the page title replaces it."""
    lines = body.split("\n")
    for index, line in enumerate(lines):
        if not line.strip():
            continue
        if line.startswith("# "):
            del lines[index]
        break
    return "\n".join(lines).lstrip("\n")


def render_page(catalogue, commit, version):
    front = frontmatter().dump({
        "title": TITLE,
        "type": "reference",
        "description": DESCRIPTION,
        "lang": "en",
        "persona": "administrator",
        "app": APP,
        "source": [RELEASE.as_posix()],
        "mcp_commit": commit,
        "generated": True,
    })
    intro = (
        f"This page is the tool catalogue of the Odoo MCP server this release ships, "
        f"version {version} at commit [`{commit[:12]}`](https://github.com/{GITHUB_REPOSITORY}/commit/{commit}), "
        f"copied from its own documentation. Links to the server's other documents open "
        f"that same commit on GitHub. Bump the pin in `{RELEASE.as_posix()}`, then run "
        f"`make docs-mcp` to regenerate it; edits to the page itself are overwritten."
    )
    body = _pin_links(_demote_title(catalogue), commit).rstrip("\n") + "\n"
    return front + "\n" + "\n".join([GENERATED_NOTE, "", f"# {TITLE}", "", intro, "", body])


def rendered(repository=None, root=ROOT):
    commit, version = pinned(root)
    return render_page(fetch_catalogue(commit, repository), commit, version)


# --- Entry points ------------------------------------------------------------


def _display(path):
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def render(repository=None, root=ROOT, docs_root=USERS):
    """Write the page when it differs from the pinned catalogue. Returns the paths written."""
    text = rendered(repository, root)
    page = docs_root / PAGE
    if page.exists() and page.read_text(encoding="utf-8") == text:
        return []
    page.parent.mkdir(parents=True, exist_ok=True)
    page.write_text(text, encoding="utf-8")
    return [page]


def check(repository=None, root=ROOT, docs_root=USERS):
    """Return ``(path, problem)`` when the committed page is not the pinned catalogue."""
    text = rendered(repository, root)
    page = docs_root / PAGE
    if not page.exists():
        return [(_display(page), "missing; run `make docs-mcp`")]
    if page.read_text(encoding="utf-8") != text:
        return [(_display(page), "differs from the pinned odoo-mcp catalogue; run `make docs-mcp`")]
    return []
